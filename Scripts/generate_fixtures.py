# PDF
# --------------------------------------------------------------------------- #

PDF_PAGES = [
    (
        "iBiblio Sample Document",
        [
            "This PDF was generated by Scripts/generate_fixtures.py.",
            "It gives the Readium PDF renderer a real document to lay out,",
            "so pagination, search and metadata can be demonstrated offline.",
        ],
    ),
    (
        "Rendering Notes",
        [
            "Readium serves this file over its own resource server so that",
            "the PDF engine can request byte ranges without any extra work",
            "from the app. Nothing here needs network access.",
        ],
    ),
]


def _pdf_escape(text: str) -> str:
    return text.replace("\\", r"\\").replace("(", r"\(").replace(")", r"\)")


def build_pdf(path: Path) -> None:
    objects: list[bytes] = []

    def add(body: bytes) -> int:
        objects.append(body)
        return len(objects)  # 1-based object number

    catalog_id = add(b"")  # 1, patched below
    pages_id = add(b"")  # 2, patched below
    font_id = add(
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica "
        b"/Encoding /WinAnsiEncoding >>"
    )

    page_ids: list[int] = []
    for title, lines in PDF_PAGES:
        stream_parts = [
            b"BT",
            b"/F1 22 Tf",
            b"72 720 Td",
            b"(%s) Tj" % _pdf_escape(title).encode("latin-1"),
            b"/F1 12 Tf",
            b"0 -28 Td",
        ]
        for line in lines:
            stream_parts.append(b"(%s) Tj" % _pdf_escape(line).encode("latin-1"))
            stream_parts.append(b"0 -18 Td")
        stream_parts.append(b"ET")
        content = b"\n".join(stream_parts)

        content_id = add(
            b"<< /Length %d >>\nstream\n%s\nendstream" % (len(content), content)
        )
        page_ids.append(
            add(
                b"<< /Type /Page /Parent %d 0 R /MediaBox [0 0 612 792] "
                b"/Resources << /Font << /F1 %d 0 R >> >> /Contents %d 0 R >>"
                % (pages_id, font_id, content_id)
            )
        )

    kids = b" ".join(b"%d 0 R" % pid for pid in page_ids)
    objects[pages_id - 1] = (
        b"<< /Type /Pages /Count %d /Kids [%s] >>" % (len(page_ids), kids)
    )
    objects[catalog_id - 1] = b"<< /Type /Catalog /Pages %d 0 R >>" % pages_id

    out = bytearray(b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n")
    offsets = [0]
    for number, body in enumerate(objects, start=1):
        offsets.append(len(out))
        out += b"%d 0 obj\n" % number + body + b"\nendobj\n"

    xref_at = len(out)
    out += b"xref\n0 %d\n" % (len(objects) + 1)
    out += b"0000000000 65535 f \n"
    for offset in offsets[1:]:
        out += b"%010d 00000 n \n" % offset
    out += b"trailer\n<< /Size %d /Root %d 0 R >>\nstartxref\n%d\n%%%%EOF\n" % (
        len(objects) + 1,
        catalog_id,
        xref_at,
    )

    path.write_bytes(bytes(out))


# --------------------------------------------------------------------------- #
# Audiobook
# --------------------------------------------------------------------------- #

SAMPLE_RATE = 22_050
DURATION_SECONDS = 3.0
TONE_HZ = 220.0


def build_wav(path: Path) -> None:
    frame_count = int(SAMPLE_RATE * DURATION_SECONDS)
    amplitude = 0.35

    frames = bytearray()
    for index in range(frame_count):
        t = index / SAMPLE_RATE
        # A short sweep plus an amplitude envelope, so the sample sounds like a
        # deliberate test tone rather than a click.
        sweep = TONE_HZ + (TONE_HZ / 2) * (t / DURATION_SECONDS)
        envelope = min(1.0, min(t, DURATION_SECONDS - t) / 0.05)
        sample = amplitude * envelope * math.sin(2 * math.pi * sweep * t)
        frames += struct.pack("<h", int(max(-1.0, min(1.0, sample)) * 32_767))

    data = bytes(frames)
    header = b"RIFF" + struct.pack("<I", 36 + len(data)) + b"WAVE"
    header += b"fmt " + struct.pack(
        "<IHHIIHH",
        16,          # PCM header size
        1,           # PCM
        1,           # mono
        SAMPLE_RATE,
        SAMPLE_RATE * 2,  # byte rate
        2,           # block align
        16,          # bits per sample
    )
    header += b"data" + struct.pack("<I", len(data))
    path.write_bytes(header + data)


