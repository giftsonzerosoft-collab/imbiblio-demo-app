#!/usr/bin/env python3
"""Generate the EPUB / PDF / audiobook fixtures bundled with the app.

Everything is written with the standard library only, so this runs anywhere
Python does -- no `pip install`, no Calibre, no ffmpeg. The generated files
are byte-for-byte valid enough for Readium to open on device:

  * EPUB  -- a real ZIP (stored, uncompressed) with an OCF package document,
            `mimetype`, `META-INF/container.xml` and a valid OPF manifest.
  * PDF   -- a hand-written PDF 1.4 file with two pages of text.
  * WAV   -- 16-bit PCM mono, 3 s of a sine sweep, so `AudioNavigator` has
            something to play and seek.

Run:  python Scripts/generate_fixtures.py
"""

from __future__ import annotations

import math
import struct
import sys
import zipfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = REPO_ROOT / "App" / "Resources" / "Fixtures"

# The mimetype entry must be first and STORED (uncompressed) per the OCF spec,
# so the ZIP is written entry-by-entry rather than with `zipfile.write`.
MIMETYPE = "application/epub+zip"


# --------------------------------------------------------------------------- #
# EPUB
# --------------------------------------------------------------------------- #

CONTAINER_XML = """<?xml version="1.0" encoding="UTF-8"?>
<container version="1.0" xmlns="urn:oasis:names:tc:opendocument:xmlns:container">
  <rootfiles>
    <rootfile full-path="OEBPS/content.opf" media-type="application/oebps-package+xml"/>
  </rootfiles>
</container>
"""

CHAPTERS = [
    (
        "The Offline Library",
        [
            "This publication was generated by Scripts/generate_fixtures.py.",
            "It exists so the demo can be opened, paginated and read on a "
            "device without shipping any copyrighted material.",
            "Readium parses the package document below and lays out each XHTML "
            "resource as a navigable document.",
        ],
    ),
    (
        "Uploads and Readium",
        [
            "Uploading runs through iBiblioCore, which knows nothing about "
            "Readium. That separation is deliberate: it keeps every byte of "
            "business logic testable on any platform.",
            "Readium only appears when a publication is opened for reading, "
            "and again when it is opened from a remote URL rather than a local "
            "file.",
            "The two halves meet in a single adapter that turns a catalog entry "
            "into a view controller.",
        ],
    ),
    (
        "Colophon",
        [
            "Set in the system serif face at whatever size the reader "
            "preferences ask for.",
            "The file you are reading is about six kilobytes long and was "
            "generated deterministically, so the build is reproducible.",
        ],
    ),
]


def _xhtml(title: str, paragraphs: list[str]) -> str:
    body = "\n".join(f"    <p>{p}</p>" for p in paragraphs)
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE html>
<html xmlns="http://www.w3.org/1999/xhtml" xml:lang="en" lang="en">
  <head>
    <title>{title}</title>
    <meta charset="utf-8"/>
    <link rel="stylesheet" type="text/css" href="style.css"/>
  </head>
  <body>
    <h1>{title}</h1>
{body}
  </body>
</html>
"""


def _nav_document(entries: list[tuple[str, str]]) -> str:
    items = "\n".join(
        f'    <li><a href="{href}">{label}</a></li>' for label, href in entries
    )
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE html>
<html xmlns="http://www.w3.org/1999/xhtml" xmlns:epub="http://www.idpf.org/2007/ops" xml:lang="en">
  <head><title>Contents</title></head>
  <body>
    <nav epub:type="toc" id="toc">
      <h1>Contents</h1>
      <ol>
{items}
      </ol>
    </nav>
  </body>
</html>
"""


STYLE_CSS = """body { font-family: serif; line-height: 1.5; margin: 1em; }
h1 { font-size: 1.6em; line-height: 1.2; }
p { text-align: justify; hyphens: auto; }
"""


def build_epub(path: Path) -> None:
    chapter_items = [
        (title, f"chapter{index + 1}.xhtml")
        for index, (title, _) in enumerate(CHAPTERS)
    ]

    manifest = [
        '    <item id="nav" href="nav.xhtml" media-type="application/xhtml+xml" properties="nav"/>',
        '    <item id="style" href="style.css" media-type="text/css"/>',
    ]
    spine = []
    for index, (title, href) in enumerate(chapter_items, start=1):
        manifest.append(
            f'    <item id="ch{index}" href="{href}" media-type="application/xhtml+xml"/>'
        )
        spine.append(f'    <itemref idref="ch{index}"/>')

    opf = f"""<?xml version="1.0" encoding="UTF-8"?>
<package xmlns="http://www.idpf.org/2007/opf" version="3.0" unique-identifier="bookid">
  <metadata xmlns:dc="http://purl.org/dc/elements/1.1/">
    <dc:identifier id="bookid">urn:uuid:0b8f0c1e-6c1a-4f3b-9d0e-7a2b5c4d3e2f</dc:identifier>
    <dc:title>iBiblio Sample Publication</dc:title>
    <dc:creator>iBiblio Demo</dc:creator>
    <dc:language>en</dc:language>
    <dc:description>Generated fixture for the iBiblio Readium demo.</dc:description>
    <meta property="dcterms:modified">2026-01-01T00:00:00Z</meta>
  </metadata>
  <manifest>
{chr(10).join(manifest)}
  </manifest>
  <spine>
{chr(10).join(spine)}
  </spine>
</package>
"""

    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as archive:
        # OCF requires the mimetype entry first, stored, with no extra field.
        info = zipfile.ZipInfo("mimetype", date_time=(2026, 1, 1, 0, 0, 0))
        info.compress_type = zipfile.ZIP_STORED
        archive.writestr(info, MIMETYPE)

        archive.writestr("META-INF/container.xml", CONTAINER_XML)
        archive.writestr("OEBPS/style.css", STYLE_CSS)
        archive.writestr("OEBPS/nav.xhtml", _nav_document(chapter_items))
        for index, (title, paragraphs) in enumerate(CHAPTERS, start=1):
            archive.writestr(
                f"OEBPS/chapter{index}.xhtml", _xhtml(title, paragraphs)
            )
        archive.writestr("OEBPS/content.opf", opf)


