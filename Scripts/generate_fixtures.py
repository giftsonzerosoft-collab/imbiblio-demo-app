def build_sidecar(path: Path) -> None:
    """A tiny JSON sidecar so the app can list fixtures without unzipping.

    The ids here are *unprefixed*. `LibraryEntry.id` in the app adds a
    `fixture-` prefix so a bundled publication can never collide with a remote
    catalog entry that happens to share an id, so emitting the prefix here too
    would produce `fixture-fixture-epub`.
    """
    import json

    payload = {
        "publications": [
            {
                "id": "epub",
                "title": "iBiblio Sample Publication",
                "author": "iBiblio Demo",
                "format": "epub",
                "fileName": "sample.epub",
            },
            {
                "id": "pdf",
                "title": "iBiblio Sample Document",
                "author": "iBiblio Demo",
                "format": "pdf",
                "fileName": "sample.pdf",
            },
            {
                "id": "audiobook",
                "title": "iBiblio Test Tone",
                "author": "iBiblio Demo",
                "format": "audiobook",
                "fileName": "sample.wav",
            },
        ]
    }
    path.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")


# --------------------------------------------------------------------------- #


def main() -> int:
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    build_epub(OUT_DIR / "sample.epub")
    build_pdf(OUT_DIR / "sample.pdf")
    build_wav(OUT_DIR / "sample.wav")
    build_sidecar(OUT_DIR / "manifest.json")

    for name in ("sample.epub", "sample.pdf", "sample.wav", "manifest.json"):
        size = (OUT_DIR / name).stat().st_size
        print(f"  {name:16} {size:>8,} bytes")

    print(f"\nWrote fixtures to {OUT_DIR}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
